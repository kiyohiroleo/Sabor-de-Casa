-- Tabela Categoria
CREATE TABLE public.categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    nome TEXT NOT NULL UNIQUE
);

-- Tabela Pratos
CREATE TABLE public.pratos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    nome TEXT NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    disponivel BOOLEAN DEFAULT TRUE,
    categoria_id BIGINT NOT NULL,

    CONSTRAINT pratos_preco_positivo
        CHECK (preco > 0),

    CONSTRAINT pratos_categoria_id_fkey
        FOREIGN KEY (categoria_id)
        REFERENCES public.categoria(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Segurança por linha
ALTER TABLE public.categoria ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pratos ENABLE ROW LEVEL SECURITY;

-- Políticas de leitura pública
CREATE POLICY "Leitura publica de categorias"
ON public.categoria
FOR SELECT
TO anon
USING (true);

CREATE POLICY "Leitura publica de pratos"
ON public.pratos
FOR SELECT
TO anon
USING (true);